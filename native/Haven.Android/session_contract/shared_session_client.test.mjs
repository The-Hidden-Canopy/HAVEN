import assert from 'node:assert/strict';
import {SharedSessionClient} from './shared_session_client.mjs';
const calls=[];
let response={ok:true,contract:'haven-session-1',operations:['sessions','replay','submit','cancel','command_status'],guarantees:['durable_replay','idempotent_commands']};
const client=new SharedSessionClient({async call(tool,args,id){calls.push({tool,args,id});return response;}});
await assert.rejects(client.sessions('before'),/capability_unavailable/);
await client.capabilities('caps-1');
response={ok:true,contract:'haven-session-1',session_id:'shared',events:[{seq:1,kind:'message'}],next_cursor:1};
await client.replay('shared',0,'replay-1');
assert.equal(calls[1].tool,'haven.session.replay');
assert.equal(calls[1].args.version,'haven-session-1');
assert.equal(calls[1].id,'replay-1');
response={ok:true,contract:'haven-session-1',session_id:'wrong',events:[],next_cursor:0};
await assert.rejects(client.replay('shared',0,'replay-2'),/incompatible_session/);
response={ok:true,contract:'haven-session-1',session_id:'shared',events:[{seq:2}],next_cursor:2};
await assert.rejects(client.replay('shared',0,'replay-3'),/replay_gap/);
response={ok:true,contract:'haven-session-1',session_id:'shared',state:'unknown'};
assert.equal((await client.commandStatus('shared','command-1','status-1')).state,'unknown');
response={ok:false,code:'access_denied'};
await assert.rejects(client.submit('shared','hello','command-1'),/session_unavailable_or_denied/);
assert.equal(calls.filter(x=>x.id==='command-1').length,1);
await assert.rejects(client.cancel('shared','job',''),/stable request ID/);
response={ok:true,contract:'haven-session-1',operations:['replay','submit'],guarantees:[]};await client.capabilities('caps-2');
await assert.rejects(client.replay('shared',0,'r4'),/capability_unavailable/);
await assert.rejects(client.submit('shared','hello','c2'),/capability_unavailable/);
console.log('Provider-neutral web session adapter tests passed');
